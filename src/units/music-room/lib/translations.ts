export type TranslationKey = keyof typeof Copy.ru

export const translate = (locale: Locale, key: TranslationKey) => i18next.getFixedT(locale)(key)

export const translateGenre = (locale: Locale, genre: string) => {
  const keys: Record<string, TranslationKey> = {
    Все: 'genreAll',
    Джаз: 'genreJazz',
    Инди: 'genreIndie',
    'Хип-хоп': 'genreHipHop',
    Рок: 'genreRock',
    Электроника: 'genreElectronic',
    'Лоу-фай': 'genreLoFi',
    Эмбиент: 'genreAmbient',
  }
  const key = keys[genre]
  return key ? translate(locale, key) : genre
}

export const translateRoomName = (locale: Locale, name: string) => {
  const names: Record<string, TranslationKey> = {
    'Ночной джаз': 'roomNightJazz',
    Винил: 'roomVinyl',
    'Инди-волна': 'roomIndieWave',
    'Тихий фокус': 'roomQuietFocus',
    'Плейлист друзей': 'roomFriendsPlaylist',
  }
  const key = names[name]
  return key ? translate(locale, key) : name
}

export const translateTrackTitle = (locale: Locale, title: string) => {
  const titles: Record<string, TranslationKey> = {
    'Планы на это лето': 'songPlans',
    'На Киевском Динамо': 'songRave',
    Утро: 'songMorning',
    Иордания: 'songJordan',
  }
  const key = titles[title]
  return locale === 'en' && key ? translate(locale, key) : title
}

export const translateMockMessage = (locale: Locale, id: string, text: string) => {
  if (locale === 'ru') return text
  const messages: Record<string, TranslationKey> = {
    'jazz-1': 'chatJazz1',
    'jazz-2': 'chatJazz2',
    'vinyl-1': 'chatVinyl1',
    'vinyl-2': 'chatVinyl2',
    'wave-1': 'chatWave1',
    'wave-2': 'chatWave2',
    'focus-1': 'chatFocus1',
    'playlist-1': 'chatPlaylist1',
    'playlist-2': 'chatPlaylist2',
  }
  if (id.startsWith('welcome-')) return translate(locale, 'welcomeMessage')
  const key = messages[id]
  return key ? translate(locale, key) : text
}

export const formatListeners = (locale: Locale, count: number) => {
  const form = new Intl.PluralRules(locale).select(count)
  const label = translate(locale, form === 'one' ? 'listener' : 'listeners')
  return `${count} ${label}`
}

export const formatTrackCount = (locale: Locale, count: number) => {
  const form = new Intl.PluralRules(locale).select(count)
  const key = form === 'one' ? 'track' : form === 'few' ? 'tracksFew' : 'tracksMany'
  const label = translate(locale, key)
  return `${count} ${label}`
}
